import assert from 'node:assert/strict';
import {initial,mutate} from '../src/model.ts';
import {classHistory} from '../src/class-history.ts';
const s=initial(2),g=s.groups[0].id,other=s.groups[1].id;
mutate(s,{action:'addStudents',names:'Ada\nBen',group:g});mutate(s,{action:'addStudents',names:'Clara',group:other});
for(const date of ['2026-10-01','2026-10-08','2026-10-15','2026-10-22'])mutate(s,{action:'session',date});
const [ada,ben]=s.students.filter(p=>p.group===g);
const [d1,d2,d3,d4]=s.sessions;
Object.assign(d1.marks,{[ada.id]:'abwesend',[ben.id]:'anwesend'});d1.reports[g]='2026-10-01T10:00:00Z';
Object.assign(d2.marks,{[ada.id]:'abwesend',[ben.id]:'entschuldigt'});d2.reports[g]='2026-10-08T10:00:00Z';d2.cancelled='';
d3.cancelled='Ferien';d3.reports[g]='2026-10-15T10:00:00Z';
d4.reports[other]='2026-10-22T10:00:00Z';
d1.roster=d1.roster.filter(p=>p.id!==ben.id);
const h=classHistory(s,g);
assert.deepEqual(h.dates,['2026-10-08','2026-10-01'],'only submitted, not cancelled lessons of this class, newest first');
assert.deepEqual(h.rows.map(r=>r.student.name),['Ada','Ben'],'only pupils of this class');
assert.deepEqual(h.rows[0].cells,['abwesend','abwesend']);assert.equal(h.rows[0].absent,2);
assert.deepEqual(h.rows[1].cells,['entschuldigt','fehlt'],'pupil missing from a historic roster');assert.equal(h.rows[1].absent,0,'excused absences are not counted');
assert.deepEqual(classHistory(initial(1),'x'),{dates:[],rows:[]});
console.log('Class history checks passed: submitted lessons only, cancelled and other classes excluded, newest first, roster gaps and unexcused counter.');
